const $ = (selector, root = document) => root.querySelector(selector);
const $$ = (selector, root = document) => [...root.querySelectorAll(selector)];

// Защита текста от случайных HTML-символов
function esc(text) {
  return String(text).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

// 15000 → «15 000 ₸»
function formatPrice(value) {
  return value.toLocaleString('ru-RU').replace(/\s/g, ' ') + ' ₸';
}

function whatsappLink(number, message) {
  return `https://wa.me/${number}?text=${encodeURIComponent(message)}`;
}

const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

/* Загрузка фото: адаптивные размеры + запасной вариант при ошибке */
function setImage(img, id, alt, sizes) {
  const frame = img.closest('.img-frame');
  if (frame) frame.classList.remove('is-broken');
  img.onerror = () => frame && frame.classList.add('is-broken');
  img.alt = alt;
  if (!id.includes('/') && !id.includes('.')) {
    img.srcset = [600, 1000, 1600, 2200].map((w) => `${photoUrl(id, w)} ${w}w`).join(', ');
    img.sizes = sizes;
  } else {
    img.removeAttribute('srcset');
  }
  img.src = photoUrl(id, 1200);
}

