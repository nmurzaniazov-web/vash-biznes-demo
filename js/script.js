/* ---------- Переключение типа бизнеса ---------- */
function setBusiness(key, animate = true) {
  if (!BUSINESSES[key] || key === current) return;
  current = key;

  // Состояние кнопок переключателя
  $$('.switcher__btn').forEach((btn) => {
    const active = btn.dataset.key === key;
    btn.setAttribute('aria-checked', String(active));
    btn.tabIndex = active ? 0 : -1;
  });
  scrollChipIntoView();

  // Адрес страницы: ?biz=barber — такую ссылку можно отправить клиенту
  const url = new URL(window.location.href);
  url.searchParams.set('biz', key);
  history.replaceState(null, '', url);

  const apply = () => {
    document.body.dataset.business = key;
    render(key);
  };

  if (!animate || reduceMotion) {
    apply();
    return;
  }
  document.body.classList.add('is-swapping');
  setTimeout(() => {
    apply();
    requestAnimationFrame(() => document.body.classList.remove('is-swapping'));
  }, 320);
}

function buildSwitcher() {
  const list = $('[data-list="switcher"]');
  list.innerHTML = Object.entries(BUSINESSES).map(([key, b]) =>
    `<button class="switcher__btn" type="button" role="radio" aria-checked="false" data-key="${key}">${icon(b.icon)}<span>${esc(b.label)}</span></button>`
  ).join('');

  list.addEventListener('click', (e) => {
    const btn = e.target.closest('.switcher__btn');
    if (btn) setBusiness(btn.dataset.key);
  });

  // Управление стрелками клавиатуры
  list.addEventListener('keydown', (e) => {
    const keys = Object.keys(BUSINESSES);
    const step = { ArrowRight: 1, ArrowDown: 1, ArrowLeft: -1, ArrowUp: -1 }[e.key];
    if (!step) return;
    e.preventDefault();
    const next = keys[(keys.indexOf(current) + step + keys.length) % keys.length];
    setBusiness(next);
    $(`.switcher__btn[data-key="${next}"]`).focus();
  });
}

// На телефоне прокручиваем ленту так, чтобы выбранная кнопка была видна
function scrollChipIntoView() {
  const list = $('.switcher__list');
  const btn = $('.switcher__btn[aria-checked="true"]');
  if (!list || !btn) return;
  const left = btn.offsetLeft - (list.clientWidth - btn.offsetWidth) / 2;
  list.scrollTo({ left, behavior: reduceMotion ? 'auto' : 'smooth' });
}

/* ---------- Мобильное меню ---------- */
function initMenu() {
  const burger = $('#burger');
  const nav = $('#nav');

  const toggle = (open) => {
    burger.setAttribute('aria-expanded', String(open));
    burger.setAttribute('aria-label', open ? 'Закрыть меню' : 'Открыть меню');
    nav.classList.toggle('is-open', open);
    document.body.classList.toggle('menu-open', open);
  };

  burger.addEventListener('click', () => toggle(burger.getAttribute('aria-expanded') !== 'true'));
  nav.addEventListener('click', (e) => { if (e.target.closest('a')) toggle(false); });
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && nav.classList.contains('is-open')) { toggle(false); burger.focus(); }
  });
  window.matchMedia('(min-width: 1141px)').addEventListener('change', (e) => { if (e.matches) toggle(false); });
}

/* ---------- Шапка: фон при прокрутке и активный пункт меню ---------- */
function initHeader() {
  const header = $('#header');
  const update = () => header.classList.toggle('is-solid', window.scrollY > 40);
  update();
  window.addEventListener('scroll', update, { passive: true });

  const links = $$('.nav__link');
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      links.forEach((l) => l.classList.toggle('is-active', l.getAttribute('href') === `#${entry.target.id}`));
    });
  }, { rootMargin: '-45% 0px -50% 0px' });
  $$('main section[id]').forEach((s) => observer.observe(s));
}

/* ---------- FAQ: открытие и закрытие ответов ---------- */
function initFaq() {
  $('[data-list="faq"]').addEventListener('click', (e) => {
    const btn = e.target.closest('.faq__question');
    if (!btn) return;
    const item = btn.closest('.faq__item');
    const willOpen = !item.classList.contains('is-open');

    // Закрываем остальные ответы, чтобы список оставался аккуратным
    $$('.faq__item.is-open').forEach((other) => {
      other.classList.remove('is-open');
      $('.faq__question', other).setAttribute('aria-expanded', 'false');
    });

    item.classList.toggle('is-open', willOpen);
    btn.setAttribute('aria-expanded', String(willOpen));
  });
}

/* ---------- Плавное появление блоков при прокрутке ---------- */
let revealObserver = null;

function observeReveals() {
  if (!('IntersectionObserver' in window) || reduceMotion) {
    $$('.reveal').forEach((el) => el.classList.add('is-visible'));
    return;
  }
  if (!revealObserver) {
    revealObserver = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible');
          revealObserver.unobserve(entry.target);
        }
      });
    }, { rootMargin: '0px 0px -8% 0px', threshold: 0.08 });
  }
  $$('.reveal:not(.is-visible)').forEach((el) => revealObserver.observe(el));
}

/* ---------- Просмотр фото из галереи ---------- */
function initLightbox() {
  const box = $('#lightbox');
  const img = $('.lightbox__img', box);
  const caption = $('.lightbox__caption', box);
  let index = 0;
  let lastFocus = null;

  const show = (i) => {
    const items = BUSINESSES[current].gallery;
    index = (i + items.length) % items.length;
    const [id, text] = items[index];
    img.src = photoUrl(id, 1800);
    img.alt = text;
    caption.textContent = `${text} · ${index + 1} из ${items.length}`;
  };

  const open = (i) => {
    lastFocus = document.activeElement;
    show(i);
    box.hidden = false;
    document.body.classList.add('menu-open');
    $('.lightbox__close', box).focus();
  };

  const close = () => {
    box.hidden = true;
    document.body.classList.remove('menu-open');
    if (lastFocus) lastFocus.focus();
  };

  $('[data-list="gallery"]').addEventListener('click', (e) => {
    const item = e.target.closest('.gallery__item');
    if (item) open(Number(item.dataset.index));
  });

  $('.lightbox__close', box).addEventListener('click', close);
  $('.lightbox__prev', box).addEventListener('click', () => show(index - 1));
  $('.lightbox__next', box).addEventListener('click', () => show(index + 1));
  box.addEventListener('click', (e) => { if (e.target === box) close(); });

  document.addEventListener('keydown', (e) => {
    if (box.hidden) return;
    if (e.key === 'Escape') close();
    if (e.key === 'ArrowLeft') show(index - 1);
    if (e.key === 'ArrowRight') show(index + 1);
    // Держим фокус внутри окна просмотра
    if (e.key === 'Tab') {
      const buttons = $$('.lightbox__btn', box);
      const first = buttons[0];
      const last = buttons[buttons.length - 1];
      if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
      else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
    }
  });

  // Листание свайпом на телефоне
  let startX = 0;
  box.addEventListener('touchstart', (e) => { startX = e.touches[0].clientX; }, { passive: true });
  box.addEventListener('touchend', (e) => {
    const dx = e.changedTouches[0].clientX - startX;
    if (Math.abs(dx) > 50) show(index + (dx < 0 ? 1 : -1));
  });
}

